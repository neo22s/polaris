<?php

declare(strict_types=1);

namespace Polaris\Deploy;

use RuntimeException;

/**
 * Builds the one-off PHP script that applies pending SQL on the server.
 *
 * The script is uploaded into the document root, called once over HTTPS with a
 * random token, and removes itself before doing anything else. It carries the
 * token, so it must never outlive the request: a stray copy in the web root
 * with a valid token is a remote schema-writer.
 *
 * It is generated rather than shipped as a file so the token and the SQL never
 * touch the repository, and so an old build cannot be reused by mistake.
 */
final class RemoteRunner
{
    /**
     * @param array<string,string> $migrations name => SQL
     */
    public static function build(array $migrations, string $token): string
    {
        // The token is a short hex string, so var_export is safe. The SQL is
        // arbitrary text: base64 keeps dollar signs, quotes and PHP tags from
        // being parsed as code. A JSON literal embedded in the script would
        // interpolate dollar signs because it sits inside a double-quoted string.
        $tokenLiteral = var_export($token, true);
        $migrationsLiteral = var_export(base64_encode((string) json_encode(
            $migrations,
            JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE,
        )), true);

        return <<<PHP
<?php
// Generated by Polaris. Applies migrations once, then removes itself.
// The token travels in the POST body, never in the URL: URLs end up in access
// logs. Deleting before the check also makes a stray copy impossible to probe.
@unlink(__FILE__);

if (strtoupper((string) (\$_SERVER['REQUEST_METHOD'] ?? 'GET')) !== 'POST') {
    http_response_code(405);
    exit('forbidden');
}

\$token = (string) (\$_POST['t'] ?? '');

if (!hash_equals({$tokenLiteral}, \$token)) {
    http_response_code(403);
    exit('forbidden');
}

header('Content-Type: text/plain; charset=utf-8');

\$root = __DIR__;
require \$root . '/vendor/autoload.php';

try {
    \$settings = require \$root . '/config/settings.php';
    \$db = new Polaris\\Support\\Database(\$settings['settings']['db']);
    \$migrations = json_decode((string) base64_decode({$migrationsLiteral}, true), true);

    if (!is_array(\$migrations)) {
        throw new \RuntimeException('Invalid migration payload.');
    }

    // The runner carries the SQL, so it does not depend on the files having
    // been uploaded yet. It records the names through the same runner the rest
    // of the project uses, so a later deploy sees them as applied.
    \$pdo = \$db->pdo();
    \$pdo->exec('CREATE TABLE IF NOT EXISTS `_migrations` (
        `id` int unsigned NOT NULL AUTO_INCREMENT,
        `migration_name` varchar(191) NOT NULL,
        `applied_at` datetime NOT NULL,
        PRIMARY KEY (`id`),
        UNIQUE KEY `migration_name` (`migration_name`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci');

    \$applied = [];
    foreach (\$pdo->query('SELECT migration_name FROM _migrations') as \$row) {
        \$applied[(string) \$row['migration_name']] = true;
    }

    \$count = 0;
    foreach (\$migrations as \$name => \$sql) {
        if (isset(\$applied[\$name])) {
            continue;
        }

        try {
            \$pdo->exec(\$sql);
        } catch (\\Throwable \$e) {
            throw new \\RuntimeException('Migration ' . \$name . ' failed: ' . \$e->getMessage(), 0, \$e);
        }

        \$stmt = \$pdo->prepare('INSERT INTO _migrations (migration_name, applied_at) VALUES (:n, :a)');
        \$stmt->execute(['n' => \$name, 'a' => \\Polaris\\Support\\Clock::now()]);
        \$count++;
    }

    echo 'OK ' . \$count;
} catch (\\Throwable \$e) {
    http_response_code(500);
    echo 'ERR: ' . \$e->getMessage();
} finally {
    @unlink(__FILE__);
}
PHP;
    }

    /**
     * Collect every upgrade file of a site, keyed by the name recorded in
     * `_migrations`.
     *
     * @param array<int,string> $directories
     * @return array<string,string> name => SQL
     */
    public static function collect(array $directories): array
    {
        $migrations = [];

        foreach ($directories as $directory) {
            foreach (glob(rtrim($directory, '/') . '/*.sql') ?: [] as $path) {
                $name = basename($path);
                $sql = trim((string) file_get_contents($path));

                if ($sql !== '') {
                    $migrations[$name] = $sql;
                }
            }
        }

        ksort($migrations);

        return $migrations;
    }
}
